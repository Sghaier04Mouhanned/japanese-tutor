# Entries that aren't meanings: big-number units (10**16) and the "kokuji" tag.
_JUNK = re.compile(r"\*\*|\(kokuji\)")
_NOTE = re.compile(r"\s*\([^)]*\)")


def cue(ch: str, meanings: list[str]) -> list[str]:
    """Meanings safe to show when the kanji itself is the answer: drops notes like
    "(一緒)" that contain the kanji, so "together (一緒)" becomes "together"."""
    # One shared pattern: a pattern per kanji would overflow re's cache with 2,000 kanji.
    return [_NOTE.sub(lambda note: "" if ch in note.group() else note.group(), m) for m in meanings]


def learner_first(ch: str, meanings: list[str], limit: int = 5) -> list[str]:
    """KANJIDIC's meanings with the learner meanings first, junk dropped, no repeats."""
    first = LEARNER_MEANINGS[ch].split(", ") if ch in LEARNER_MEANINGS else []
    seen = {m.lower() for m in first + cue(ch, first)}  # "backbone (風呂 = bath)" covers "backbone"
    rest = [m for m in meanings if not _JUNK.search(m) and m.lower() not in seen]
    return (first + rest)[:limit]
